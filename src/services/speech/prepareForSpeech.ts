/**
 * TTS 向けの読み替え。画面表示はそのまま、読み上げだけ桁の誤読を防ぐ。
 * 安全性・通知・Expo Speech の共通前処理。
 */

/**
 * 緊急番号・相談番号など、桁のまま読むと誤読されやすい表記を直す。
 */
export function prepareTextForSpeech(text: string): string {
  let t = (text ?? '').trim();
  if (!t) {
    return '';
  }

  // #9110（シャープくじゅういちゼロ）→ 読みだけ残す（二重読み防止）
  t = t.replace(
    /#\s*9110\s*[（(]\s*シャープくじゅういちゼロ\s*[）)]/g,
    'シャープくじゅういちゼロ',
  );
  t = t.replace(/#\s*9110/g, 'シャープくじゅういちゼロ');

  // 119 → いちいちきゅう（前後が数字でないときだけ）
  t = t.replace(/(^|[^0-9])119(?![0-9])/g, '$1いちいちきゅう');

  return t;
}
